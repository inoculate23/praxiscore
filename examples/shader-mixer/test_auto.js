'use strict';
const assert=require('node:assert/strict');
const AutoMixer=require('./player/auto-mode.js');
let prepared=[],position=.5;
const auto=new AutoMixer({setFade:x=>position=x,prepare:deck=>prepared.push(deck)});
auto.configure({enabled:true,hold_seconds:2,fade_seconds:.5},.5);
for(let i=0;i<3;i++)auto.tick(.25);
assert.equal(position,1);assert.deepEqual(prepared,[],'Starting from a mixed image must not replace an audible shader');
for(let i=0;i<8;i++)auto.tick(.25);
assert.deepEqual(prepared,[0],'Only hidden A can be replaced');
for(let i=0;i<2;i++)auto.tick(.25);
assert.equal(position,0);
auto.configure({enabled:false});const old=position;
for(let i=0;i<50;i++)auto.tick(.25);
assert.equal(position,old);
assert.throws(()=>auto.configure({hold_seconds:0}));
assert.throws(()=>auto.configure({fade_seconds:NaN}));
assert.throws(()=>auto.configure({pool:'unknown'}));
auto.next(position);assert.equal(auto.settings.enabled,true);
auto.tick(.1);assert.equal(auto.phase,'fade');assert.equal(prepared.at(-1),1);
console.log('Auto checks passed: safe hidden-deck changes, endpoint transitions, stop, next, settings validation.');
